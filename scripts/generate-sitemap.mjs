/**
 * Pre-build: 生成 public/sitemap.xml 与 public/robots.txt。
 *
 * Slug 计算逻辑与 scripts/generate-params.mjs 保持一致（index.mdx → 父路径，
 * 不产出 "index" 段）。URL 为生产环境绝对地址：GitHub Pages 项目站点 =
 * https://ddddjaak.github.io + next.config.ts 的 basePath —— 仓库改名时
 * 只需同步 next.config.ts，本脚本自动跟随。
 *
 * 运行：node scripts/generate-sitemap.mjs（prebuild 自动执行）
 */
import { writeFileSync, readdirSync, existsSync, readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const contentDir = join(root, 'content', 'docs');
const publicDir = join(root, 'public');

// ---------- 从 next.config.ts 提取 basePath ----------
const nextConfig = readFileSync(join(root, 'next.config.ts'), 'utf8');
const basePathMatch = nextConfig.match(/basePath:\s*'([^']+)'/);
if (!basePathMatch) {
  throw new Error('basePath not found in next.config.ts');
}
const basePath = basePathMatch[1].replace(/\/$/, ''); // 去掉可能的尾斜杠
const origin = 'https://ddddjaak.github.io';

// ---------- 与 generate-params.mjs 相同的 slug 遍历 ----------
const slugs = [];
function walkDir(dir, parentSlugs = []) {
  const entries = readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name === 'meta.json') continue;
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      walkDir(fullPath, [...parentSlugs, entry.name]);
    } else if (entry.name.endsWith('.mdx')) {
      const name = entry.name.replace(/\.mdx$/, '');
      if (name === 'index') {
        slugs.push([...parentSlugs]);
      } else {
        slugs.push([...parentSlugs, name]);
      }
    }
  }
}
walkDir(contentDir);

const seen = new Set();
const uniqueSlugs = slugs.filter((s) => {
  const key = s.join('/');
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

// ---------- 组装 URL（next.config trailingSlash: true → 以 / 结尾） ----------
const lastmod = new Date().toISOString().slice(0, 10);
const urls = [
  `${origin}${basePath}/`,
  ...uniqueSlugs.map((s) => `${origin}${basePath}/docs/${s.join('/')}/`),
];

const sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Auto-generated by scripts/generate-sitemap.mjs — do not edit -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url>\n    <loc>${u}</loc>\n    <lastmod>${lastmod}</lastmod>\n  </url>`).join('\n')}
</urlset>
`;

const robotsTxt = `# Auto-generated by scripts/generate-sitemap.mjs — do not edit
User-agent: *
Allow: /

Sitemap: ${origin}${basePath}/sitemap.xml
`;

writeFileSync(join(publicDir, 'sitemap.xml'), sitemapXml);
writeFileSync(join(publicDir, 'robots.txt'), robotsTxt);
console.log(`sitemap.xml: ${urls.length} URLs; robots.txt written (basePath: ${basePath})`);
